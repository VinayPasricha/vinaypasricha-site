/* =============================================================
   Organizational Frequency — Emergent Outcome Engine  (Build 1I)
   =============================================================
   Builds on 1A–1H WITHOUT changing the architecture.

   1H framed empty containers. 1I FILLS them with reasoned,
   traceable HYPOTHESES — never predictions, never scores.

   The question, always:

       "What future becomes more likely if THIS person enters
        THIS role inside THIS organization pursuing THIS mission?"

   Never: "Is this person a fit?"

   Resonance is productive emergence, surfaced as possible
   futures across 30 / 90 / 180 / 365 days.

   HARD CONSTRAINTS:
     • Reads ONLY validated / derived inputs (frequencies, gap,
       role, person, validated understanding, traceability).
       Unvalidated research is never read as truth.
     • Output is hypotheses with hedged language ("may become
       more likely", "could create", "appears likely") — NEVER
       "will", "best fit", "match", "score", "ranked".
     • Confidence is DESCRIPTIVE (low|medium|high|mixed|unknown),
       never numeric, never invented.
     • Every statement carries assumptions + traceability. If it
       cannot be traced, it is not stated strongly.
     • Memory stays gated: writes ONLY into the 1H outcome
       containers. Nothing else is touched.

   Augments window.OF.outcome with .generate / .clearGenerated.
   ============================================================= */
(function () {
  'use strict';
  if (!window.OF || !window.OF.outcome) { console.warn('of-emergence.js requires of-outcome.js'); return; }
  var OF = window.OF;
  var O = OF.outcome;

  var LEVELS = (OF.frequency && OF.frequency.LEVELS) || ['low', 'moderate', 'high', 'very_high'];
  var human = (OF.frequency && OF.frequency.human) || function (l) { return l === 'very_high' ? 'very high' : l; };
  var HORIZONS = O.TIME_HORIZONS; // ['30_days','90_days','180_days','365_days']

  function nowISO() { return new Date().toISOString(); }
  function lc(s) { return (s == null) ? s : String(s).toLowerCase(); }
  function idx(l) { return LEVELS.indexOf(l); }

  /* ---- the item every filled vector holds ------------------- */
  function item(text, horizon, confidence, evidence, reasoning) {
    return { text: text, horizon: horizon, confidence: confidence, evidence: evidence || [], reasoning: reasoning || '' };
  }

  /* ==========================================================
     GENERATE — fill one framed outcome's six containers.
     Idempotent: regenerating overwrites prior generated content.
     ========================================================== */
  function generate(outcomeId, store) {
    store = O.ensure(store || OF.load());
    var d = O.getForOutcome(outcomeId, store);
    if (!d || !d.outcome) return null;

    var ctx = buildContext(d, store);
    if (!ctx.role_frequency || !ctx.person_frequency) {
      // Cannot reason without both validated frequencies. Leave a
      // single honest, low-confidence note rather than invent.
      ctx.missingFrequencies = true;
    }

    var base = assessConfidence(ctx);

    fillMission(ctx, d.mission_outcome, base);
    fillPerson(ctx, d.person_outcome, base);
    fillOrganization(ctx, d.organization_outcome, base);
    fillCapability(ctx, d.capability_outcome, base);
    fillRisk(ctx, d.risk_outcome, base);
    fillEvolution(ctx, d.evolution_outcome, base);

    // mark the emergent outcome as generated + overall descriptive confidence
    var o = d.outcome;
    o.generated = true;
    o.generated_at = nowISO();
    o.stale = false;            // 1L: regenerating clears the stale flag
    o.stale_reason = '';
    o.confidence = base.overall; // descriptive string — NOT a score
    o.reasoning = ctx.missingFrequencies
      ? 'Both a validated role frequency and a validated person frequency are needed to reason over emergence. One or both is missing, so these containers hold only low-confidence notes.'
      : 'Generated by comparing the role frequency (what the role requires) against the person frequency (what is validated about the person), read against the organization\u2019s frequency gap and the mission. Per-dimension, hedged, and traceable. Emergent hypotheses, not predictions.';
    o.updated_at = nowISO();

    OF.save(store);
    return O.getForOutcome(outcomeId, store);
  }

  function clearGenerated(outcomeId, store) {
    store = O.ensure(store || OF.load());
    var d = O.getForOutcome(outcomeId, store);
    if (!d) return null;
    [d.mission_outcome, d.person_outcome, d.organization_outcome, d.capability_outcome, d.risk_outcome, d.evolution_outcome]
      .forEach(function (s) {
        if (!s) return;
        ['positive_trajectories', 'negative_trajectories', 'growth_vectors', 'stagnation_vectors', 'stress_vectors',
         'capability_gains', 'capability_losses', 'cultural_effects', 'capabilities_strengthened', 'capabilities_weakened',
         'identified_risks', 'risk_mitigations'].forEach(function (k) { if (Array.isArray(s[k])) s[k] = []; });
        ['summary', 'organization_evolution', 'person_evolution', 'role_evolution', 'reasoning'].forEach(function (k) { if (k in s) s[k] = ''; });
        s.assumptions = []; s.evidence = []; s.confidence = null; s.generated = false; s.generated_at = null;
      });
    d.outcome.generated = false; d.outcome.generated_at = null; d.outcome.confidence = null; d.outcome.reasoning = '';
    OF.save(store);
    return O.getForOutcome(outcomeId, store);
  }

  /* ==========================================================
     CONTEXT — assemble the validated inputs (only these)
     ========================================================== */
  function buildContext(d, store) {
    var role = d.role, person = d.person, mission = d.mission, org = d.organization;
    var rf = (store.role_frequencies || []).filter(function (x) { return role && x.role_id === role.role_id; })[0] || null;
    var pf = (store.person_frequencies || []).filter(function (x) { return person && x.person_id === person.person_id; })[0] || null;
    var gap = (store.frequency_gaps || []).filter(function (x) { return mission && x.mission_id === mission.mission_id; })[0] || null;
    var contrib = (store.role_contributions || []).filter(function (x) { return role && x.role_id === role.role_id; })[0] || null;

    var rfByDim = indexBy(rf && rf.dimensions, 'dimension');
    var pfByDim = indexBy(pf && pf.dimensions, 'dimension');
    var gapByDim = indexBy(gap && gap.dimension_gaps, 'dimension');

    var coreDim = role ? role.dimension : null;

    // per-dimension comparison: role requires vs person validated, vs org gap
    var dims = LEVELS && (OF.person ? OF.person.DIMENSIONS : (OF.frequency ? OF.frequency.DIMENSIONS : []));
    var comparison = (dims || []).map(function (name) {
      var r = rfByDim[name], p = pfByDim[name], g = gapByDim[name];
      var roleReq = r ? r.required_level : null;
      var personLvl = p ? p.level : 'unknown';
      var validated = (personLvl && personLvl !== 'unknown');
      var relation = classify(roleReq, personLvl);
      return {
        dimension: name,
        role_required: roleReq,
        role_primary: !!(r && r.primary) || name === coreDim,
        person_level: personLvl,
        person_validated: validated,
        org_current: g ? g.current_level : 'unknown',
        org_gap_level: g ? g.gap_level : 'unknown',
        relation: relation
      };
    });

    return {
      role: role, person: person, mission: mission, organization: org,
      role_frequency: rf, person_frequency: pf, gap: gap, contribution: contrib,
      core: comparison.filter(function (c) { return c.role_primary; })[0] || null,
      comparison: comparison,
      missingFrequencies: false
    };
  }

  // role-required vs person-validated relation
  function classify(roleReq, personLvl) {
    if (!roleReq || !personLvl || personLvl === 'unknown') return 'unknown';
    var diff = idx(roleReq) - idx(personLvl);
    if (diff <= -2) return 'exceeds_strong';
    if (diff === -1) return 'exceeds';
    if (diff === 0) return 'aligned';
    if (diff === 1) return 'stretch';
    return 'wide_gap';
  }

  /* ==========================================================
     CONFIDENCE MODEL — descriptive, never numeric, never certain
     ========================================================== */
  function assessConfidence(ctx) {
    if (ctx.missingFrequencies || !ctx.person_frequency) {
      return { overall: 'unknown', nValidated: 0, nUnknown: 10, conflict: false };
    }
    var comp = ctx.comparison;
    var nValidated = comp.filter(function (c) { return c.person_validated && c.role_required; }).length;
    var nUnknown = comp.filter(function (c) { return c.relation === 'unknown'; }).length;
    var aligned = comp.filter(function (c) { return c.relation === 'aligned' || c.relation === 'stretch'; }).length;
    var wide = comp.filter(function (c) { return c.relation === 'wide_gap'; }).length;
    var conflict = aligned > 0 && wide > 0;

    var role = ctx.role, mission = ctx.mission;
    var roleClear = role && (role.role_stage === 'validated' || role.role_stage === 'active' || (role.confidence || 0) >= 0.5);
    var missionClear = mission && /defined|active|urgent/.test(mission.mission_stage || '');

    var overall;
    if (nValidated >= 6 && nUnknown <= 2 && roleClear && missionClear && !conflict) overall = 'high';
    else if (nValidated <= 2 || nUnknown >= 7) overall = 'low';
    else if (conflict) overall = 'mixed';
    else overall = 'medium';

    return { overall: overall, nValidated: nValidated, nUnknown: nUnknown, conflict: conflict, wide: wide, aligned: aligned, roleClear: roleClear, missionClear: missionClear };
  }

  // a sub-outcome may sit one notch below the base (longer horizon /
  // fragile assumptions). Order: high > medium > mixed > low > unknown.
  var CONF_ORDER = ['high', 'medium', 'mixed', 'low', 'unknown'];
  function downgrade(conf, notches) {
    var i = CONF_ORDER.indexOf(conf);
    if (i === -1) return conf;
    return CONF_ORDER[Math.min(CONF_ORDER.length - 1, i + (notches || 1))];
  }

  /* ---- evidence ref helpers --------------------------------- */
  function refRoleFreq(ctx, dim) {
    return ctx.role_frequency ? { kind: 'role_frequency', ref_id: ctx.role_frequency.role_frequency_id, label: dim + ' required ' + human(reqOf(ctx, dim)) } : null;
  }
  function refPersonFreq(ctx, dim) {
    return ctx.person_frequency ? { kind: 'person_frequency', ref_id: ctx.person_frequency.person_frequency_id, label: dim + ' validated ' + human(lvlOf(ctx, dim)) } : null;
  }
  function refGap(ctx) {
    return ctx.gap ? { kind: 'frequency_gap', ref_id: ctx.gap.gap_id, label: ctx.gap.gap_summary } : null;
  }
  function refRole(ctx) {
    return ctx.role ? { kind: 'role', ref_id: ctx.role.role_id, label: ctx.role.role_name + ' — ' + (ctx.role.role_purpose || '').slice(0, 70) } : null;
  }
  function refMission(ctx) {
    return ctx.mission ? { kind: 'mission', ref_id: ctx.mission.mission_id, label: ctx.mission.mission_name || 'mission' } : null;
  }
  function reqOf(ctx, dim) { var c = byDim(ctx, dim); return c ? c.role_required : null; }
  function lvlOf(ctx, dim) { var c = byDim(ctx, dim); return c ? c.person_level : 'unknown'; }
  function byDim(ctx, dim) { return ctx.comparison.filter(function (c) { return c.dimension === dim; })[0] || null; }
  function refs() { return Array.prototype.slice.call(arguments).filter(Boolean); }
  function whoP(ctx) { return (ctx.person && ctx.person.name) || 'this person'; }
  function whoO(ctx) { return (ctx.organization && ctx.organization.organization_name) || 'the organization'; }
  function roleName(ctx) { return (ctx.role && ctx.role.role_name) || 'the role'; }

  /* ==========================================================
     MISSION OUTCOME — does this person in this role make the
     mission more executable?
     ========================================================== */
  function fillMission(ctx, mo, base) {
    if (!mo) return;
    var pos = [], neg = [];
    var core = ctx.core;

    if (!ctx.missingFrequencies && core) {
      if (core.relation === 'aligned' || core.relation === 'stretch') {
        pos.push(item(
          'On ' + lc(core.dimension) + ' — the dimension this role exists to raise — ' + whoP(ctx) +
          ' appears able to carry what the role requires, so the gap the role targets may begin to narrow.',
          '90_days', base.overall,
          refs(refRoleFreq(ctx, core.dimension), refPersonFreq(ctx, core.dimension), refGap(ctx)),
          'Core role dimension ' + core.relation + ': required ' + human(core.role_required) + ' vs person ' + human(core.person_level) + '.'));
      } else if (core.relation === 'wide_gap') {
        neg.push(item(
          'On ' + lc(core.dimension) + ', the role appears to ask more than ' + whoP(ctx) +
          ' currently brings, so progress on the gap it targets may be slower than the mission needs.',
          '180_days', downgrade(base.overall, 0),
          refs(refRoleFreq(ctx, core.dimension), refPersonFreq(ctx, core.dimension), refGap(ctx)),
          'Core role dimension wide gap: required ' + human(core.role_required) + ' vs person ' + human(core.person_level) + '.'));
      } else if (core.relation === 'unknown') {
        neg.push(item(
          'The core dimension this role targets (' + lc(core.dimension) + ') is not yet validated for ' + whoP(ctx) +
          ', so its effect on mission execution remains unclear.',
          '30_days', 'unknown',
          refs(refRoleFreq(ctx, core.dimension), refGap(ctx)),
          'Core dimension person-side unvalidated.'));
      }
    }

    // other dimensions where the person is strong and the org currently reads low
    ctx.comparison.forEach(function (c) {
      if (c === core) return;
      if (c.person_validated && idx(c.person_level) >= idx('high') && (c.org_gap_level === 'moderate' || c.org_gap_level === 'major')) {
        pos.push(item(
          'Execution on ' + lc(c.dimension) + ' may strengthen — ' + whoP(ctx) + ' reads ' + human(c.person_level) +
          ' there, where the organization currently appears to have a ' + c.org_gap_level + ' gap.',
          '180_days', downgrade(base.overall, 1),
          refs(refPersonFreq(ctx, c.dimension), refGap(ctx)),
          'Person strong on ' + c.dimension + '; org ' + c.org_gap_level + ' gap.'));
      }
    });

    // mission urgency vs pace
    var pace = byDim(ctx, 'Pace');
    if (ctx.mission && /urgent|blocked/.test(ctx.mission.mission_stage || '') && pace && pace.person_validated) {
      if (idx(pace.person_level) >= idx('high')) {
        pos.push(item('Under the mission\u2019s compressed timeline, early execution pace may hold — ' + whoP(ctx) + ' reads ' + human(pace.person_level) + ' on pace.',
          '30_days', base.overall, refs(refPersonFreq(ctx, 'Pace'), refMission(ctx)), 'Urgent mission + person high pace.'));
      } else if (idx(pace.person_level) <= idx('moderate')) {
        neg.push(item('Under the mission\u2019s compressed timeline, a steadier pace may create early friction — ' + whoP(ctx) + ' reads ' + human(pace.person_level) + ' on pace.',
          '30_days', base.overall, refs(refPersonFreq(ctx, 'Pace'), refMission(ctx)), 'Urgent mission + person lower pace.'));
      }
    }

    mo.positive_trajectories = cap(pos, 3);
    mo.negative_trajectories = cap(neg, 3);
    mo.summary = ctx.missingFrequencies
      ? 'Mission effect cannot be reasoned without both validated frequencies.'
      : (pos.length >= neg.length
        ? whoP(ctx) + ' in the ' + roleName(ctx) + ' role may make the mission somewhat more executable, chiefly through ' + (core ? lc(core.dimension) : 'the role\u2019s core dimension') + '. Held as a hypothesis.'
        : whoP(ctx) + ' in the ' + roleName(ctx) + ' role may help in places but could also slow the mission where the role asks more than is validated. Held as a hypothesis.');
    mo.confidence = core && core.relation !== 'unknown' ? base.overall : downgrade(base.overall, 1);
    mo.assumptions = ['This assumes the role keeps a focused mandate on the ' + (core ? lc(core.dimension) : 'gap') + ' it targets.',
      'This assumes mission priorities remain stable over the horizon.'];
    mo.evidence = refs(refMission(ctx), refRole(ctx), refGap(ctx));
    mo.reasoning = 'Mission executability read from the core role dimension\u2019s alignment, secondary strengths against the org gap, and mission urgency vs pace.';
    mo.generated = true; mo.generated_at = nowISO();
  }

  /* ==========================================================
     PERSON OUTCOME — what becomes more likely for the person?
     ========================================================== */
  function fillPerson(ctx, po, base) {
    if (!po) return;
    var growth = [], stag = [], stress = [];

    ctx.comparison.forEach(function (c) {
      if (!c.person_validated || !c.role_required) return;
      if (c.relation === 'stretch') {
        growth.push(item('The role may stretch ' + lc(c.dimension) + ' productively — it asks for ' + human(c.role_required) +
          ' where ' + whoP(ctx) + ' currently reads ' + human(c.person_level) + ', a likely area of growth.',
          '180_days', base.overall, refs(refRoleFreq(ctx, c.dimension), refPersonFreq(ctx, c.dimension)),
          'Stretch on ' + c.dimension + '.'));
      } else if (c.relation === 'wide_gap') {
        stress.push(item('The distance between what the role asks on ' + lc(c.dimension) + ' (' + human(c.role_required) +
          ') and where ' + whoP(ctx) + ' currently reads (' + human(c.person_level) + ') may accumulate as stress.',
          '90_days', base.overall, refs(refRoleFreq(ctx, c.dimension), refPersonFreq(ctx, c.dimension)),
          'Wide gap on ' + c.dimension + '.'));
      } else if (c.relation === 'exceeds_strong') {
        stag.push(item(lc(c.dimension) + ' may be under-used — ' + whoP(ctx) + ' reads ' + human(c.person_level) +
          ' where the role only asks for ' + human(c.role_required) + ', a possible source of stagnation.',
          '180_days', downgrade(base.overall, 1), refs(refRoleFreq(ctx, c.dimension), refPersonFreq(ctx, c.dimension)),
          'Person exceeds role need on ' + c.dimension + '.'));
      }
    });

    // leadership / people-development exposure
    var lead = byDim(ctx, 'Leadership Style'), pdev = byDim(ctx, 'People Development Orientation');
    if (ctx.core && (ctx.core.dimension === 'Leadership Style' || ctx.core.dimension === 'People Development Orientation') &&
        ctx.core.person_validated && idx(ctx.core.person_level) >= idx('moderate')) {
      growth.push(item('This role may develop ' + whoP(ctx) + '\u2019s leadership and people-development as it asks them to build a layer around the work.',
        '365_days', downgrade(base.overall, 1), refs(refRole(ctx), refPersonFreq(ctx, ctx.core.dimension)),
        'Core role dimension is leadership/people-development.'));
    }

    // autonomy friction → stress (constrained autonomy)
    var aut = byDim(ctx, 'Autonomy Level');
    if (aut && aut.person_validated && idx(aut.person_level) >= idx('high') && aut.role_required && idx(aut.role_required) <= idx('moderate')) {
      stress.push(item('Constrained autonomy may create early friction — ' + whoP(ctx) + ' reads ' + human(aut.person_level) +
        ' on autonomy where the role appears to offer less.',
        '30_days', base.overall, refs(refPersonFreq(ctx, 'Autonomy Level'), refRoleFreq(ctx, 'Autonomy Level')),
        'Person high autonomy vs lower role autonomy.'));
    }

    po.growth_vectors = cap(growth, 3);
    po.stagnation_vectors = cap(stag, 2);
    po.stress_vectors = cap(stress, 3);
    po.summary = ctx.missingFrequencies
      ? 'Person effect cannot be reasoned without both validated frequencies.'
      : 'For ' + whoP(ctx) + ', this role may open ' + growth.length + ' area' + (growth.length === 1 ? '' : 's') + ' of growth' +
        (stress.length ? ', with ' + stress.length + ' possible source' + (stress.length === 1 ? '' : 's') + ' of stress to watch' : '') + '. Held as a hypothesis.';
    po.confidence = base.overall;
    po.assumptions = ['This assumes onboarding gives ' + whoP(ctx) + ' enough context to use their strengths.',
      'This assumes ' + whoP(ctx) + ' is not overloaded by ambiguity early on.'];
    po.evidence = refs(refPersonFreq(ctx, ctx.core ? ctx.core.dimension : 'Autonomy Level'), refRole(ctx));
    po.reasoning = 'Growth from productive stretch, stress from wide gaps, stagnation from dimensions the role under-uses.';
    po.generated = true; po.generated_at = nowISO();
  }

  /* ==========================================================
     ORGANIZATION OUTCOME — what becomes more likely for the org?
     ========================================================== */
  function fillOrganization(ctx, oo, base) {
    if (!oo) return;
    var gains = [], losses = [], culture = [];
    var core = ctx.core;

    if (core && (core.relation === 'aligned' || core.relation === 'stretch')) {
      gains.push(item(whoO(ctx) + ' may gain ' + lc(core.dimension) + ' capacity it currently appears to lack' +
        (core.org_gap_level !== 'unknown' && core.org_gap_level !== 'none' ? ' (a ' + core.org_gap_level + ' gap today)' : '') + '.',
        '180_days', base.overall, refs(refGap(ctx), refPersonFreq(ctx, core.dimension), refRole(ctx)),
        'Core dimension alignment closes org gap.'));
    }
    ctx.comparison.forEach(function (c) {
      if (c === core) return;
      if (c.person_validated && idx(c.person_level) >= idx('high') && (c.org_gap_level === 'moderate' || c.org_gap_level === 'major')) {
        gains.push(item(lc(c.dimension) + ' may strengthen across the organization as ' + whoP(ctx) + ' brings ' + human(c.person_level) + ' there.',
          '180_days', downgrade(base.overall, 1), refs(refPersonFreq(ctx, c.dimension), refGap(ctx)),
          'Secondary strength vs org gap on ' + c.dimension + '.'));
      }
    });

    // cultural effects: trust, communication, people development
    ['Trust / Goodness Layer', 'Communication Style', 'People Development Orientation'].forEach(function (name) {
      var c = byDim(ctx, name);
      if (!c || !c.person_validated) return;
      if (idx(c.person_level) >= idx('high')) {
        culture.push(item('The ' + lc(name) + ' may strengthen as ' + whoP(ctx) + ' reads ' + human(c.person_level) + ' there.',
          '90_days', downgrade(base.overall, 1), refs(refPersonFreq(ctx, name)), 'Person high on cultural dimension ' + name + '.'));
      } else if (idx(c.person_level) <= idx('low') && c.role_required && idx(c.role_required) >= idx('high')) {
        culture.push(item(lc(name) + ' norms may be tested where the role appears to ask more than is validated of ' + whoP(ctx) + '.',
          '90_days', downgrade(base.overall, 1), refs(refPersonFreq(ctx, name), refRoleFreq(ctx, name)), 'Person low on cultural dimension the role needs.'));
      }
    });

    // a cautious possible loss: concentration of attention
    if (core && (core.relation === 'aligned' || core.relation === 'stretch')) {
      losses.push(item('If attention concentrates on ' + lc(core.dimension) + ', focus on other areas may thin for a time.',
        '90_days', downgrade(base.overall, 1), refs(refRole(ctx)), 'Concentration of a new role on its core dimension.'));
    }

    oo.capability_gains = cap(gains, 3);
    oo.capability_losses = cap(losses, 2);
    oo.cultural_effects = cap(culture, 3);
    oo.summary = ctx.missingFrequencies
      ? 'Organization effect cannot be reasoned without both validated frequencies.'
      : whoO(ctx) + ' may gain capacity chiefly on ' + (core ? lc(core.dimension) : 'the role\u2019s core dimension') +
        ', with cultural effects to watch. Held as a hypothesis.';
    oo.confidence = base.overall;
    oo.assumptions = ['This assumes the organization absorbs the role rather than isolating it.',
      'This assumes the role receives sufficient authority to act.'];
    oo.evidence = refs(refGap(ctx), refRole(ctx), refMission(ctx));
    oo.reasoning = 'Org gains read from the role closing its core gap and the person\u2019s secondary strengths; cultural effects from trust, communication and people-development dimensions.';
    oo.generated = true; oo.generated_at = nowISO();
  }

  /* ==========================================================
     CAPABILITY OUTCOME — which capabilities strengthen / weaken?
     ========================================================== */
  function fillCapability(ctx, co, base) {
    if (!co) return;
    var strong = [], weak = [];
    ctx.comparison.forEach(function (c) {
      if (!c.role_required) return;
      if (c.person_validated && idx(c.person_level) >= idx('high') && idx(c.role_required) >= idx('high')) {
        strong.push(item(lc(c.dimension) + ' may strengthen — the role asks for ' + human(c.role_required) +
          ' and ' + whoP(ctx) + ' reads ' + human(c.person_level) + '.',
          c.role_primary ? '90_days' : '180_days', base.overall,
          refs(refRoleFreq(ctx, c.dimension), refPersonFreq(ctx, c.dimension)), c.dimension + ' both role-needed and person-strong.'));
      } else if (c.relation === 'wide_gap' && idx(c.role_required) >= idx('high')) {
        weak.push(item(lc(c.dimension) + ' may remain thin — the role appears to need ' + human(c.role_required) +
          ' where ' + whoP(ctx) + ' currently reads ' + human(c.person_level) + ', so the capability may not form on its own.',
          '180_days', base.overall, refs(refRoleFreq(ctx, c.dimension), refPersonFreq(ctx, c.dimension)), 'Wide gap on a high-need dimension.'));
      }
    });
    co.capabilities_strengthened = cap(strong, 4);
    co.capabilities_weakened = cap(weak, 3);
    co.confidence = base.overall;
    co.assumptions = ['This assumes capability forms through the work rather than requiring separate investment.'];
    co.evidence = refs(
      ctx.role_frequency ? { kind: 'role_frequency', ref_id: ctx.role_frequency.role_frequency_id, label: ctx.role_frequency.frequency_summary } : null,
      ctx.person_frequency ? { kind: 'person_frequency', ref_id: ctx.person_frequency.person_frequency_id, label: ctx.person_frequency.frequency_summary } : null);
    co.reasoning = 'Capabilities strengthen where the role needs a dimension and the person reads strong; they may stay thin where a high-need dimension sits in a wide gap.';
    co.generated = true; co.generated_at = nowISO();
  }

  /* ==========================================================
     RISK OUTCOME — what could go wrong? (risks + mitigations)
     ========================================================== */
  function fillRisk(ctx, ro, base) {
    if (!ro) return;
    var risks = [], mits = [];
    function pair(riskText, mitText, horizon, conf, ev, reason) {
      risks.push(item(riskText, horizon, conf, ev, reason));
      mits.push(item(mitText, horizon, conf, ev, reason));
    }

    var core = ctx.core;
    if (core && core.relation === 'wide_gap') {
      pair('Overload — the core dimension (' + lc(core.dimension) + ') may ask more than ' + whoP(ctx) + ' currently brings.',
        'May require scoping the role narrowly at first and pairing ' + whoP(ctx) + ' with support on ' + lc(core.dimension) + '.',
        '90_days', base.overall, refs(refRoleFreq(ctx, core.dimension), refPersonFreq(ctx, core.dimension)), 'Core wide gap.');
    }
    var aut = byDim(ctx, 'Autonomy Level');
    if (aut && aut.person_validated && idx(aut.person_level) >= idx('high') && aut.role_required && idx(aut.role_required) <= idx('moderate')) {
      pair('Autonomy mismatch — ' + whoP(ctx) + ' reads high on autonomy where the role appears to offer less, which may create manager dependency or friction.',
        'May require clarifying decision rights early so autonomy is explicit.',
        '30_days', base.overall, refs(refPersonFreq(ctx, 'Autonomy Level'), refRoleFreq(ctx, 'Autonomy Level')), 'Autonomy mismatch.');
    }
    // authority / role clarity
    if (ctx.role && ctx.role.role_stage === 'defined' && (ctx.role.priority === 'high' || ctx.role.priority === 'critical')) {
      pair('Authority mismatch — the role is defined but not yet active, so it may lack the authority its priority implies.',
        'May require granting an explicit mandate before the horizon begins.',
        '30_days', downgrade(base.overall, 1), refs(refRole(ctx)), 'High-priority role still only defined.');
    }
    if (ctx.role && (ctx.role.confidence || 0) < 0.45) {
      pair('Role ambiguity — the role\u2019s definition is still low-confidence, so early expectations may be unclear.',
        'May require writing a sharp success definition for the first 30 days.',
        '30_days', downgrade(base.overall, 1), refs(refRole(ctx)), 'Low role confidence.');
    }
    // burnout under urgent mission + multiple wide gaps
    var wideCount = ctx.comparison.filter(function (c) { return c.relation === 'wide_gap'; }).length;
    if (ctx.mission && /urgent|blocked/.test(ctx.mission.mission_stage || '') && wideCount >= 2) {
      pair('Burnout — an urgent mission alongside several wide dimension gaps may press hard on ' + whoP(ctx) + ' early.',
        'May require staging the mission\u2019s demands so they do not all land at once.',
        '90_days', base.overall, refs(refMission(ctx), refGap(ctx)), 'Urgent mission + ' + wideCount + ' wide gaps.');
    }
    // mission drift under emerging mission
    if (ctx.mission && /emerging/.test(ctx.mission.mission_stage || '')) {
      pair('Mission drift — the mission is still emerging, so the role\u2019s target may move under ' + whoP(ctx) + '.',
        'May require revisiting the role purpose if the mission shifts.',
        '180_days', downgrade(base.overall, 1), refs(refMission(ctx), refRole(ctx)), 'Emerging mission stage.');
    }
    if (!risks.length) {
      pair('No sharp risk stands out on the validated dimensions — but unknowns remain.',
        'May require validating the unknown dimensions before relying on this read.',
        '90_days', 'mixed', refs(refRole(ctx), refGap(ctx)), 'No wide gaps on validated dimensions.');
    }

    ro.identified_risks = cap(risks, 4);
    ro.risk_mitigations = cap(mits, 4);
    ro.confidence = base.conflict ? 'mixed' : base.overall;
    ro.assumptions = ['This assumes early signals of overload or friction are noticed and acted on.',
      'If these assumptions are fragile, confidence in the risk read should reduce.'];
    ro.evidence = refs(refRole(ctx), refGap(ctx), refMission(ctx));
    ro.reasoning = 'Risks read from wide gaps (overload), autonomy/authority mismatches, role ambiguity, and mission stage. Each risk carries a paired, hedged mitigation.';
    ro.generated = true; ro.generated_at = nowISO();
  }

  /* ==========================================================
     EVOLUTION OUTCOME — the deepest object. How may organization,
     role and person evolve together over time?
     ========================================================== */
  function fillEvolution(ctx, eo, base) {
    if (!eo) return;
    var core = ctx.core;
    var conf = downgrade(base.overall, 1); // longest horizon, most unknowns

    if (ctx.missingFrequencies) {
      eo.organization_evolution = 'Cannot be reasoned without both validated frequencies.';
      eo.person_evolution = 'Cannot be reasoned without both validated frequencies.';
      eo.role_evolution = 'Cannot be reasoned without both validated frequencies.';
      eo.confidence = 'unknown';
      eo.assumptions = ['This assumes a validated role frequency and person frequency both exist.'];
      eo.evidence = refs(refRole(ctx), refMission(ctx));
      eo.reasoning = 'Evolution needs both sides validated before it can be read.';
      eo.generated = true; eo.generated_at = nowISO();
      return;
    }

    eo.organization_evolution = whoO(ctx) + ' may evolve from carrying a ' +
      (core && core.org_gap_level !== 'unknown' ? core.org_gap_level + ' ' + lc(core.dimension) + ' gap' : 'gap on its core dimension') +
      ' toward holding that capability internally over 180\u2013365 days, if the role takes hold — its frequency maturing rather than the founder absorbing the work. This appears likely only while the role keeps its mandate and the mission stays stable.';

    var growthDims = ctx.comparison.filter(function (c) { return c.relation === 'stretch'; }).map(function (c) { return lc(c.dimension); });
    eo.person_evolution = whoP(ctx) + ' may grow over 365 days' +
      (growthDims.length ? ' particularly on ' + growthDims.slice(0, 2).join(' and ') + ', if the stretch stays productive rather than tipping into overload' : ' if the role stretches without overwhelming') +
      '. Where the role under-uses their strengths, the longer-term risk is plateau rather than growth.';

    eo.role_evolution = 'The ' + roleName(ctx) + ' itself may need to evolve — broadening as ' + whoP(ctx) +
      ' grows into it, or being supported by a second role if the gap proves larger than one person can close. Its purpose, not its title, is what should be revisited.';

    eo.confidence = conf;
    eo.assumptions = ['This assumes the mission remains stable enough for compounding effects.',
      'This assumes the role receives sufficient authority over the full horizon.',
      'This assumes onboarding succeeds and early stress is managed.'];
    eo.evidence = refs(refMission(ctx), refRole(ctx), refGap(ctx),
      ctx.person_frequency ? { kind: 'person_frequency', ref_id: ctx.person_frequency.person_frequency_id, label: 'person frequency' } : null,
      ctx.role_frequency ? { kind: 'role_frequency', ref_id: ctx.role_frequency.role_frequency_id, label: 'role frequency' } : null);
    eo.reasoning = 'Co-evolution read across 180\u2013365 days: the org maturing its core capability, the person growing through productive stretch, and the role broadening or being supported. The deepest and least certain output — held at reduced confidence by design.';
    eo.generated = true; eo.generated_at = nowISO();
  }

  /* ---- helpers ---------------------------------------------- */
  function cap(arr, n) { return (arr || []).slice(0, n); }
  function indexBy(arr, key) { var o = {}; (arr || []).forEach(function (x) { o[x[key]] = x; }); return o; }

  // augment the existing OF.outcome surface
  O.generate = generate;
  O.clearGenerated = clearGenerated;
  O.assessConfidence = assessConfidence;
  O.CONFIDENCE_VALUES = ['low', 'medium', 'high', 'mixed', 'unknown'];
})();
