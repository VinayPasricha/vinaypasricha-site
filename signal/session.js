function renderRecordBody(text) {
  const def = sessionDef();
  const kind = def.recordKind || 'paragraphs';
  if (kind === 'structured') {
    // Per-session labels (def.recordLabels) win; legacy default is the
    // five-field Resonance Record 1 schema.
    const labels = def.recordLabels || [
      'Detected Trade', 'Avoided Cost', 'Protective Narrative',
      'Actual Price Being Paid', 'Witnessing Instruction',
    ];
    const found = {};
    // Find each label and capture everything until the next label.
    for (let i = 0; i < labels.length; i++) {
      const here = labels[i];
      const re = new RegExp('(?:^|\\n)\\s*' + here.replace(/ /g, '\\s+') + '\\s*:\\s*([\\s\\S]*?)(?=\\n\\s*(?:' + labels.filter((_, j) => j !== i).map(l => l.replace(/ /g, '\\s+')).join('|') + ')\\s*:|$)', 'i');
      const m = text.match(re);
      if (m && m[1]) found[here] = m[1].trim();
    }
    if (Object.keys(found).length === 0) {
      // Couldn't parse — fall back to paragraphs
      return paragraphsRender(text);
    }
    // The LAST present label is always rendered as the closing
    // observation block — italic, ember-bordered. By convention, the
    // witnessing / observation instruction is always last.
    const presentLabels = labels.filter(l => found[l]);
    const lastLabel = presentLabels[presentLabels.length - 1];
    return presentLabels.map(l => {
      const isLast = l === lastLabel;
      const cls = isLast ? 'srf-witness' : '';
      return `
        <div class="srf-block ${cls}">
          <div class="srf-label">${escapeHTML(l)}</div>
          <div class="srf-value">${isLast ? '<em>' + escapeHTML(found[l]) + '</em>' : escapeHTML(found[l])}</div>
        </div>
      `;
    }).join('');
  }
  return paragraphsRender(text);
}

function paragraphsRender(text) {
  const blocks = text.split(/\n\s*\n/).map(b => b.trim()).filter(Boolean);
  return blocks.map((b, i) => {
    const isLast = i === blocks.length - 1;
    return isLast ? `<p><em>${escapeHTML(b)}</em></p>` : `<p>${escapeHTML(b)}</p>`;
  }).join('');
}

