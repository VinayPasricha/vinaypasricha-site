/* ============================================================
   ATMOSPHERIC FIELD STATES
   ============================================================
   Subtle data-attribute on <body> per session arc + beat depth.
   CSS in signal.css responds with near-subconscious environmental
   shifts. The state changes automatically as the reader moves
   through the session.
   ============================================================ */
function applyAtmosphere(def, beatIdx) {
  document.body.setAttribute('data-arc', def.arc || 'Correction');
  document.body.setAttribute('data-session-id', String(def.id));
  const total = (def.beats || []).length || 1;
  let stage = 'mid';
  if (beatIdx < Math.ceil(total / 3)) stage = 'early';
  else if (beatIdx >= total - Math.floor(total / 3)) stage = 'late';
  document.body.setAttribute('data-beat-stage', stage);
}

/* ============================================================
   MEMORY THREAD
   ============================================================
   At the top of a session (other than Session 0), surface the
   closing line of the reader's most recent Resonance Record.
   Continuity, not summary. The reader feels: "the field remembers
   the work I did last session" — never "this AI knows me".

   The thread shows ONLY for fresh-start sessions, never mid-flow
   or on a re-shown completed session.
   ============================================================ */
function renderMemoryThread(def) {
  if (def.id === 0) return;                                         // first session — no prior
  if (!state.records || state.records.length === 0) return;
  if (activeSession.exchanges && activeSession.exchanges.length > 0) return;
  if (activeSession.completed) return;

  const lastRecord = state.records[state.records.length - 1];
  if (!lastRecord || !lastRecord.record) return;

  // Extract the closing line:
  //   • structured Resonance Record 1 → "Witnessing Instruction"
  //   • paragraphs record → last paragraph (the italic closing line)
  let closing = '';
  const text = String(lastRecord.record).trim();
  const witnessMatch = text.match(/Witnessing Instruction\s*:\s*([\s\S]+?)$/i);
  if (witnessMatch) {
    closing = witnessMatch[1].trim();
  } else {
    const paras = text.split(/\n\s*\n/).map(p => p.trim()).filter(Boolean);
    closing = paras[paras.length - 1] || '';
  }
  if (!closing) return;
  if (closing.length > 240) closing = closing.slice(0, 240).replace(/\s+\S*$/, '') + '…';

  const refLabel = `Session ${String(lastRecord.sessionId).padStart(2, '0')} · ${lastRecord.sessionTitle || ''}`;
  const thread = document.createElement('div');
  thread.className = 's-memory-thread';
  thread.innerHTML = `
    <div class="s-memory-label">The field remembers</div>
    <div class="s-memory-body">
      ${escapeHTML(closing)}
      <span class="s-memory-ref">— ${escapeHTML(refLabel)}</span>
    </div>
  `;
  const title = stage.querySelector('.s-stage-title');
  if (title && title.nextSibling) stage.insertBefore(thread, title.nextSibling);
  else stage.appendChild(thread);
}

function boot() {
  const def = sessionDef();
  // Atmosphere — set the room before anything else paints
  applyAtmosphere(def, beatIndex);
  // Update session id label
  if (sessionId) sessionId.innerHTML = `Session <em>${String(def.id).padStart(2, '0')}</em> · ${escapeHTML(def.title)}`;
  // Update stage eyebrow/title from session config
  const eb = document.querySelector('.s-stage-eyebrow');
  if (eb) eb.textContent = def.stageLabel || eb.textContent;
  const st = document.querySelector('.s-stage-title');
  if (st) st.innerHTML = def.stageTitle || st.innerHTML;
  if (textarea && def.inputPlaceholder) textarea.placeholder = def.inputPlaceholder;
  const pacing = document.querySelector('.s-pacing');
  if (pacing && def.pacingNote) pacing.innerHTML = def.pacingNote;
  document.title = `Session ${def.id} · ${def.title} — The Signal`;

  // Memory thread — surface continuity from the previous session, if any
  renderMemoryThread(def);

  // Render any existing exchanges (returning reader mid-session)
  for (const ex of activeSession.exchanges) {
    renderExchange(ex, false);
  }
  // Show next beat or complete session
  if (activeSession.completed) {
    // Re-show the existing record
    if (activeSession.record) {
      const recordLabel = def.recordTitle
        ? def.recordTitle + ' · Session ' + String(def.id).padStart(2, '0')
        : `Resonance Record${def.id === 0 ? '' : ' ' + def.id} · Session ${String(def.id).padStart(2, '0')}`;
      const nextHref = def.nextSessionId != null && SESSIONS[def.nextSessionId]
        ? `session.html?session=${def.nextSessionId}`
        : 'field.html';
      const nextLabel = def.nextSessionId != null && SESSIONS[def.nextSessionId]
        ? `Begin Session ${def.nextSessionId} — ${SESSIONS[def.nextSessionId].title} →`
        : 'Begin a new session';
      const recordEl = document.createElement('div');
      recordEl.className = 's-record';
      recordEl.innerHTML = `
        <div class="s-record-label">${escapeHTML(recordLabel)}</div>
        <div class="s-record-title"><em>${escapeHTML(activeSession.title)}</em></div>
        <div class="s-record-body">
          ${renderRecordBody(activeSession.record)}
        </div>
        <div class="s-record-actions">
          <a href="field.html">View the Field →</a>
          <a href="${nextHref}" class="next">${nextLabel}</a>
        </div>
      `;
      stage.appendChild(recordEl);
      inputZone.style.display = 'none';
    }
  } else if (beatIndex < def.beats.length) {
    renderPendingQuestion(def.beats[beatIndex], beatIndex === 0);
  }

  // Wire input
  textarea.addEventListener('input', autosize);
  textarea.addEventListener('keydown', (e) => {
    if (e.key === 'Enter' && (e.metaKey || e.ctrlKey)) {
      e.preventDefault();
      handleSubmit();
    }
  });
  submitBtn.addEventListener('click', handleSubmit);
}

