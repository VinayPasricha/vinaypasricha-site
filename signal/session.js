// Knowledge base storage — per-session conceptual frames that ride
// alongside the system prompt at call time. Authored in Studio → Prompts
// in the "Knowledge base" textarea. Loaded from prompts.json at boot.
const SIGNAL_REFLECTION_KB = {};   // { [sessionId: 0..8]: string }
const SIGNAL_RECORD_KB = {};

(async function loadSignalPromptOverrides() {
  let data = null;
  try {
    const draft = localStorage.getItem('studio.prompts');
    if (draft) data = JSON.parse(draft);
  } catch (e) {}
  if (!data) {
    try {
      const res = await fetch('../assets/data/prompts.json', { cache: 'no-cache' });
      if (res.ok) data = await res.json();
    } catch (e) {}
  }
  const p = (data && data.prompts) || {};
  // Session 0 — the base prompts + KB.
  const r = p['signal-reflection'] && p['signal-reflection'].system;
  const rec = p['signal-record'] && p['signal-record'].system;
  if (r && r.trim()) REFLECTION_SYSTEM = r;
  if (rec && rec.trim()) RECORD_SYSTEM = rec;
  const r0kb = p['signal-reflection'] && p['signal-reflection'].knowledge_base;
  const rec0kb = p['signal-record'] && p['signal-record'].knowledge_base;
  if (r0kb && r0kb.trim()) SIGNAL_REFLECTION_KB[0] = r0kb;
  if (rec0kb && rec0kb.trim()) SIGNAL_RECORD_KB[0] = rec0kb;
  // Sessions 1–8 — per-session system prompts AND knowledge bases.
  // Each lands on a window override key (system) and an indexed map (KB).
  // Studio → Prompts edits both surfaces.
  for (let i = 1; i <= 8; i++) {
    const refl  = p['signal-' + i + '-reflection'] && p['signal-' + i + '-reflection'].system;
    const recd  = p['signal-' + i + '-record']     && p['signal-' + i + '-record'].system;
    const rkb   = p['signal-' + i + '-reflection'] && p['signal-' + i + '-reflection'].knowledge_base;
    const reckb = p['signal-' + i + '-record']     && p['signal-' + i + '-record'].knowledge_base;
    if (refl && refl.trim()) window['__SIGNAL_SESSION_' + i + '_REFLECTION_OVERRIDE'] = refl;
    if (recd && recd.trim()) window['__SIGNAL_SESSION_' + i + '_RECORD_OVERRIDE'] = recd;
    if (rkb  && rkb.trim())   SIGNAL_REFLECTION_KB[i] = rkb;
    if (reckb && reckb.trim()) SIGNAL_RECORD_KB[i] = reckb;
  }
})();

// Per-session prompt resolution. Order of precedence:
//   1. Studio → Prompts override (window.__SIGNAL_SESSION_N_*_OVERRIDE)
//   2. Hard-coded session-specific default (SESSION_1_* etc.)
//   3. The base REFLECTION_SYSTEM / RECORD_SYSTEM (Session 0 prompt).
// Sessions 2–8 currently inherit the Session 1 defaults — the Trade
// prompt is intentionally restrained and works for all developmental beats.
// A bespoke per-session prompt should be authored in prompts.json as work
// on each session deepens.
function getReflectionSystem() {
  const id = activeSessionId();
  const ov = window['__SIGNAL_SESSION_' + id + '_REFLECTION_OVERRIDE'];
  if (ov) return ov;
  if (id === 0) return REFLECTION_SYSTEM;
  return SESSION_1_REFLECTION_DEFAULT;
}
function getRecordSystem() {
  const id = activeSessionId();
  const ov = window['__SIGNAL_SESSION_' + id + '_RECORD_OVERRIDE'];
  if (ov) return ov;
  if (id === 0) return RECORD_SYSTEM;
  return SESSION_1_RECORD_DEFAULT;
}

// Knowledge-base lookups. Empty string when no KB has been authored.
function getReflectionKnowledge() { return SIGNAL_REFLECTION_KB[activeSessionId()] || ''; }
function getRecordKnowledge()     { return SIGNAL_RECORD_KB[activeSessionId()]     || ''; }

// Compose the full Claude system surface: system prompt + (optional)
// knowledge base. The two are joined with a stable separator so the
// model can reliably distinguish the rules from the reading material.
function composeWithKnowledge(systemPrompt, kb) {
  if (!kb || !kb.trim()) return systemPrompt;
  return systemPrompt + '\n\n---\n\n# KNOWLEDGE BASE\n\n' + kb.trim();
}

