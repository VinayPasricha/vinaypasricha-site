// Active session is selected by ?session=N (defaults to 0).
function activeSessionId() {
  try {
    const id = parseInt(new URL(location).searchParams.get('session') || '0', 10);
    return SESSIONS[id] ? id : 0;
  } catch (e) { return 0; }
}
function sessionDef() { return SESSIONS[activeSessionId()]; }

/* ============================================================
   STATE
   Sessions accumulate across visits. We persist a small object.
   ============================================================ */
function loadState() {
  try {
    const raw = localStorage.getItem('signal.state');
    if (!raw) return defaultState();
    const parsed = JSON.parse(raw);
    return Object.assign(defaultState(), parsed);
  } catch (e) { return defaultState(); }
}
function defaultState() {
  return {
    firstSeen: null,
    lastSession: null,
    records: [],     // accumulated Resonance Records
    currentSession: null, // mid-session draft
  };
}
function saveState(state) {
  try { localStorage.setItem('signal.state', JSON.stringify(state)); } catch (e) {}
}

