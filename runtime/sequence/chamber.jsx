// Cache the loaded doctrine + node spec on the window so we
// don't refetch them on every turn.
async function loadGrounding() {
  if (window.kairos && window.kairos._grounding) return window.kairos._grounding;
  const out = { doctrine: '', nodeSpec: '' };
  try {
    const book = await window.library.getBook('execution-doctrine');
    if (book && book.text) {
      // Take a focused slice — the first 28k chars covers preface,
      // governing limit, capacity expansion engine, base loop, and
      // Chapter 6 (Action 1 → Action N), which is what this chamber
      // is grounded in. Keeps latency manageable.
      out.doctrine = book.text.slice(0, 28000);
    }
  } catch (e) {}
  try {
    const res = await fetch('../../_brief/runtime-nodes/01-sequence-chamber.md', { cache: 'force-cache' });
    if (res.ok) out.nodeSpec = await res.text();
  } catch (e) {}
  window.kairos = window.kairos || {};
  window.kairos._grounding = out;
  return out;
}

