/* =============================================================
   KAIROS·1 — Sequence Chamber · orchestrator
   =============================================================
   The chamber's brain. Composes the inquiry surface and the
   topology, holds runtime state, and calls Claude grounded in
   the Execution Doctrine + the Node 01 spec.

   The first turn (the opening) is hardcoded so the reader never
   waits at the door — the chamber knows how to begin. Every
   subsequent turn is generated by the runtime intelligence,
   constrained to a strict JSON contract so the topology updates
   structurally as the dialogue progresses.
   ============================================================= */

