// CHAMBER COMPONENT
// =============================================================
function Chamber() {
  const stateRef = useRef(null);
  const [, force] = useState(0);
  const tick = useCallback(() => force(x => x + 1), []);

  const [thinking, setThinking] = useState(false);
  const [errorNote, setErrorNote] = useState(null);
  const [composerLocked, setComposerLocked] = useState(false);
  const [resting, setResting] = useState(false);
  const lockTimer = useRef(null);

  // Load on mount
  useEffect(() => {
    const s = window.kairos.state.load();
    // Demo seeding (no-op unless ?demo=1) — pressure-test landmarks
    if (window.kairos.landmarks && window.kairos.landmarks.maybeSeedDemo) {
      window.kairos.landmarks.maybeSeedDemo(s);
    }
    const seq = window.kairos.state.ensureSequence(s);
    const isFresh = !seq.inquiry_log || seq.inquiry_log.length === 0;
    isFreshEntryRef.current = isFresh;
    if (isFresh) {
      OPENING.forEach(o => {
        window.kairos.state.logEntry(seq, o.role, o.content, o.kind);
      });
    }
    window.kairos.state.save(s);
    stateRef.current = s;
    tick();
    // Pre-warm grounding so the first AI call is fast
    loadGrounding().catch(() => {});
  }, [tick]);

  const state = stateRef.current;
  const seq = state && state.current_sequence;

  const handleSubmit = useCallback(async (text) => {
    if (!state || !seq) return;
    // 1. Log reader's turn
    window.kairos.state.logEntry(seq, 'reader', text);
    window.kairos.state.save(state);
    setThinking(true);
    setErrorNote(null);
    tick();

    try {
      // 2. Ask the runtime
      const reply = await askRuntime(seq, text);
      // 3. Apply structural deltas
      window.kairos.state.applyDeltas(seq, reply.deltas);
      // 4. Log runtime's turn
      window.kairos.state.logEntry(seq, 'runtime', reply.say, reply.kind);
      window.kairos.state.save(state);
      // 5. Held silence — the reader is given time to sit with what was said
      //    before the composer accepts the next response. Observations carry
      //    the longest hold because they surface structure that should land.
      const holdMs = reply.kind === 'observation' ? 2400
                    : reply.kind === 'settle'    ? 3200
                    :                              1400;
      setComposerLocked(true);
      clearTimeout(lockTimer.current);
      lockTimer.current = setTimeout(() => setComposerLocked(false), holdMs);
    } catch (e) {
      setErrorNote(
        'The runtime is not reachable from this page. ' +
        'Open the chamber from a host that provides the intelligence layer.'
      );
      console.warn('[chamber] askRuntime failed:', e);
    } finally {
      setThinking(false);
      tick();
    }
  }, [state, seq, tick]);

  // Cleanup the hold timer on unmount
  useEffect(() => () => clearTimeout(lockTimer.current), []);

  // Receive an in-flight transition handshake on mount, so the
  // page emerges rather than snapping in.
  useEffect(() => {
    if (window.kairos && window.kairos.transition) {
      window.kairos.transition.receive({ slug: 'sequence' });
    }
  }, []);

  // Spine: summonable via `S` from inside the chamber.
  const spine = (typeof useSpine === 'function') ? useSpine() : { visible: false, open: () => {}, close: () => {}, toggle: () => {} };
  // Strata: summonable via `H`. Geological memory of prior cycles.
  const strata = (typeof useStrata === 'function') ? useStrata() : { visible: false, open: () => {}, close: () => {}, toggle: () => {} };
  // Track whether this is a fresh first-entry to the chamber
  // (no prior turns AND no transition handshake). Used to hold
  // the page in darkness briefly before the chamber emerges.
  const isFreshEntryRef = useRef(false);

  // Chamber weight — the Sequence Chamber is the clearer, more
  // architectural room. Set the body attribute so atmosphere CSS
  // can differentiate this chamber from the denser Observatory.
  useEffect(() => {
    document.body.setAttribute('data-chamber', 'sequence');
    // Refinement 10: mark the visit so the threshold can carry
    // residue of the reader's prior descent on next return.
    const s = window.kairos.state.load();
    window.kairos.state.markChamberVisit(s, 'sequence');
    return () => document.body.removeAttribute('data-chamber');
  }, []);

  const enterRest = useCallback(() => {
    setResting(true);
    setComposerLocked(false);
    clearTimeout(lockTimer.current);
  }, []);
  const leaveRest = useCallback(() => setResting(false), []);

  // Hybrid sovereignty — archives current cycle, opens a fresh one.
  // The runtime never closes a cycle itself; this is reader-invoked.
  const handleCloseCycle = useCallback(() => {
    if (!state || !seq) return;
    if (seq.actions.length > 0 || seq.outcome) {
      state.history = state.history || [];
      state.history.push({ kind: 'sequence', data: seq, closed_at: Date.now() });
    }
    state.current_sequence = window.kairos.state.emptySequence();
    OPENING.forEach(o => {
      window.kairos.state.logEntry(state.current_sequence, o.role, o.content, o.kind);
    });
    window.kairos.state.save(state);
    isFreshEntryRef.current = true;
    tick();
  }, [state, seq, tick]);

  const handleReset = useCallback(() => {
    if (!window.confirm('Reset this sequence? The chamber will start again. (Your history archive is preserved.)')) return;
    if (!state || !seq) return;
    // Archive the prior sequence rather than deleting
    if (seq.actions.length > 0 || seq.outcome) {
      state.history = state.history || [];
      state.history.push({ kind: 'sequence', data: seq, closed_at: Date.now() });
    }
    state.current_sequence = window.kairos.state.emptySequence();
    OPENING.forEach(o => {
      window.kairos.state.logEntry(state.current_sequence, o.role, o.content, o.kind);
    });
    window.kairos.state.save(state);
    tick();
  }, [state, seq, tick]);

  if (!state || !seq) {
    return (
      <div style={{ padding: '80px 48px', fontFamily: 'var(--mono)', color: 'var(--ink-4)', letterSpacing: '0.3em', textTransform: 'uppercase', fontSize: 10 }}>
        Initialising…
      </div>
    );
  }

  // Telemetry computed each render
  const actionCount = seq.actions.length;
  const txCount = seq.transitions.length;
  const governing = seq.actions.find(a => a.governs_flow);
  const avgFriction = actionCount > 0
    ? seq.actions.reduce((s, a) => s + (a.friction || 0), 0) / actionCount
    : 0;
  const frictionTier = avgFriction >= 0.5 ? 'high' : (avgFriction >= 0.25 ? 'mid' : 'low');

  const turnsForUI = (seq.inquiry_log || []).map(t => ({
    role: t.role, kind: t.kind, content: t.content
  }));

  const composerHint = thinking ? 'the runtime is reading'
    : (seq.phase === 'outcome' ? 'be concrete · cmd/ctrl + enter'
      : (seq.phase === 'sequencing' ? 'one step at a time · cmd/ctrl + enter'
        : 'cmd/ctrl + enter to submit'));

  const composerPlaceholder = ({
    outcome:    'What must exist when this is complete?',
    sequencing: 'Name the next step. Be specific. Owner, completion, what comes after.',
    refining:   'Where does this slow? What lacks a completion state? What is avoided?',
    settled:    'Continue probing, or step away. The chamber will hold.',
  })[seq.phase || 'outcome'];

  // Count prior cycles for this chamber
  const priorCycles = (state.history || []).filter(h => h.kind === 'sequence' || (!h.kind && h.actions)).length;
  // Compute fresh-entry class only on the very first render
  // (when the inquiry log had just the opening turn). After any
  // reader response, the chamber is no longer "fresh."
  const isFresh = isFreshEntryRef.current && (seq.inquiry_log || []).length <= 1;

  return (
    <main className={'chamber' + (resting ? ' is-resting' : '') + (isFresh ? ' is-fresh-entry' : '') + (seq.phase === 'settled' ? ' is-settled' : '')} data-screen-label="01 Sequence Chamber">

      {/* Top bar */}
      <header className="c-top">
        <div className="c-breadcrumb">
          <a href="../index.html">KAIROS·1</a>
          <span className="sep">/</span>
          <span>Chamber 01</span>
        </div>
        <div className="c-name">
          The <em>Sequence</em> Chamber
        </div>
        <div className="c-telemetry">
          <span className="tcell phase">phase · <em>{seq.phase}</em></span>
          <span className="tcell">actions · <em>{actionCount}</em></span>
          <span className="tcell">transitions · <em>{txCount}</em></span>
          <button
            className="c-spine-glyph"
            type="button"
            onClick={spine.toggle}
            aria-label="Open the runtime spine"
            title="Open the runtime spine (S)"
          ></button>
        </div>
      </header>

      {/* Body — split */}
      <div className="c-body">

        <InquirySurface
          turns={turnsForUI}
          thinking={thinking}
          phase={seq.phase}
          composerLocked={composerLocked}
          resting={resting}
          onSubmit={handleSubmit}
          onRest={enterRest}
          onResume={leaveRest}
          onCloseCycle={handleCloseCycle}
          composerHint={composerHint}
          composerPlaceholder={composerPlaceholder}
        />

        <section className="c-topology" aria-label="The topology">
          <div className="c-topology-head">
            <span>— <em>Execution topology</em></span>
            <span className="right">
              <span>{actionCount} node{actionCount === 1 ? '' : 's'}</span>
              <span>{txCount} transition{txCount === 1 ? '' : 's'}</span>
              {governing ? <span style={{ color: 'var(--heat)' }}>· governing surfaced</span> : null}
            </span>
          </div>

          <Topology sequence={seq} history={state.history || []} />

          <div className="c-topology-foot">
            <div className="cell">
              <div className="label">Outcome</div>
              <div className="value">
                {seq.outcome ? (seq.outcome.length > 64 ? seq.outcome.slice(0, 63) + '…' : seq.outcome) : <em>undefined</em>}
              </div>
            </div>
            <div className="cell">
              <div className="label">Completion criteria</div>
              <div className="value">
                {seq.outcome_completion ? (seq.outcome_completion.length > 56 ? seq.outcome_completion.slice(0,55) + '…' : seq.outcome_completion) : <em>not yet defined</em>}
              </div>
            </div>
            <div className={'cell' + (frictionTier === 'high' ? ' high' : '')}>
              <div className="label">Mean friction</div>
              <div className="value">
                {actionCount > 0
                  ? <span><em>{avgFriction.toFixed(2)}</em> · {frictionTier}</span>
                  : <em>—</em>}
              </div>
            </div>
            <div className="cell">
              <div className="label">Governing limit</div>
              <div className="value">
                {governing
                  ? <em>{governing.id} · {(governing.label || '').slice(0, 32) || 'unnamed'}</em>
                  : <em>not yet surfaced</em>}
              </div>
            </div>
          </div>
        </section>

      </div>

      <footer className="c-actions">
        <span>session · {state.identity.sessions_count} · started {new Date(seq.started_at).toLocaleDateString('en-GB', { day: '2-digit', month: 'short', year: 'numeric' })}</span>
        <span className="c-actions-center">
          {priorCycles > 0 ? (
            <button onClick={strata.toggle} type="button" className="c-strata-link">
              prior cycles · <em>{priorCycles}</em> · H
            </button>
          ) : (
            <span className="c-strata-empty">no prior strata yet</span>
          )}
          {errorNote ? <span style={{ color: 'var(--heat-2)', marginLeft: 18 }}>{errorNote}</span> : null}
        </span>
        <span>
          <button onClick={handleReset} type="button">Reset sequence</button>
        </span>
      </footer>

      <Spine currentSlug="sequence" visible={spine.visible} onDismiss={spine.close} />
      <Strata history={state.history || []} currentChamber="sequence" visible={strata.visible} onDismiss={strata.close} />

    </main>
  );
}

